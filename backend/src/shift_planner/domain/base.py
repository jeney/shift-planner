from typing import Annotated

from pydantic import BaseModel, ConfigDict, StringConstraints
from pydantic.alias_generators import to_camel


class ApiModel(BaseModel):
    """Base for every model that crosses the API boundary.

    Python uses snake_case, JSON uses camelCase. Unknown fields are rejected so that typos and
    files from a newer app version fail loudly instead of being silently dropped.
    """

    model_config = ConfigDict(
        alias_generator=to_camel,
        validate_by_name=True,
        validate_by_alias=True,
        serialize_by_alias=True,
        extra="forbid",
        # Fields with defaults are always present in responses, so mark them required there.
        json_schema_serialization_defaults_required=True,
    )


Id = Annotated[str, StringConstraints(min_length=1, max_length=64)]
"""Opaque identifier, generated by the client (usually a UUID)."""

TimeOfDay = Annotated[str, StringConstraints(pattern=r"^(?:(?:[01]\d|2[0-3]):[0-5]\d|24:00)$")]
"""Local wall-clock time "HH:MM" (Europe/Copenhagen). "24:00" means end of day."""

YearMonth = Annotated[str, StringConstraints(pattern=r"^\d{4}-(?:0[1-9]|1[0-2])$")]
"""Planning month, "YYYY-MM"."""

HexColor = Annotated[str, StringConstraints(pattern=r"^#[0-9a-fA-F]{6}$")]


def to_minutes(time: str) -> int:
    """Convert "HH:MM" to minutes after midnight."""
    hours, minutes = time.split(":")
    return int(hours) * 60 + int(minutes)


def from_minutes(minutes: int) -> str:
    """Convert minutes after midnight to "HH:MM"."""
    return f"{minutes // 60:02d}:{minutes % 60:02d}"
